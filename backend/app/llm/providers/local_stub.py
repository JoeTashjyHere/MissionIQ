class LocalStubEmbedder:
    """Deterministic pseudo-embedder. Produces a fixed-dimension unit vector
    from the SHA-256 of the input. Useful for offline tests + demos."""

    name = _NAME

    @property
    def default_model(self) -> str:
        return "missioniq-stub-embed-1"

    @property
    def dimension(self) -> int:
        return get_settings().embedding_dim

    def is_available(self) -> bool:
        return True

    async def embed(
        self, texts: list[str], *, model: str | None = None
    ) -> EmbeddingResponse:
        start = time.perf_counter()
        embeddings: list[list[float]] = []
        dim = self.dimension
        for t in texts:
            digest = hashlib.sha256(t.encode("utf-8")).digest()
            # Expand digest deterministically to dim floats in [-1, 1].
            vec: list[float] = []
            seed = int.from_bytes(digest[:8], "big")
            x = seed or 1
            for _ in range(dim):
                x = (x * 1103515245 + 12345) & 0x7FFFFFFF
                vec.append(((x % 20001) - 10000) / 10000.0)
            norm = math.sqrt(sum(v * v for v in vec)) or 1.0
            embeddings.append([v / norm for v in vec])
        latency_ms = int((time.perf_counter() - start) * 1000)
        return EmbeddingResponse(
            embeddings=embeddings,
            provider=_NAME,
            model=model or self.default_model,
            input_tokens=sum(len(t.split()) for t in texts),
            latency_ms=latency_ms,
        )
